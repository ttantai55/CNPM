UPDATE public.users
SET role = CASE UPPER(BTRIM(role))
    WHEN 'ROLE_CUSTOMER' THEN 'CUSTOMER'
    WHEN 'CUSTOMER' THEN 'CUSTOMER'
    WHEN 'ROLE_STAFF' THEN 'STAFF'
    WHEN 'STAFF' THEN 'STAFF'
    WHEN 'ROLE_MANAGER' THEN 'MANAGER'
    WHEN 'MANAGER' THEN 'MANAGER'
    WHEN 'ROLE_ADMIN' THEN 'MANAGER'
    WHEN 'ADMIN' THEN 'MANAGER'
    ELSE role
END
WHERE role IS NOT NULL
  AND UPPER(BTRIM(role)) IN (
      'ROLE_CUSTOMER', 'CUSTOMER',
      'ROLE_STAFF', 'STAFF',
      'ROLE_MANAGER', 'MANAGER',
      'ROLE_ADMIN', 'ADMIN'
  );

UPDATE public.users
SET provider = UPPER(BTRIM(provider))
WHERE provider IS NOT NULL
  AND provider <> UPPER(BTRIM(provider));
